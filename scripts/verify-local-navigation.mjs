import { _electron as electron, expect } from '@playwright/test';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
const folder = await mkdtemp(path.join(tmpdir(), 'nexo-navigation-'));
let app;
try {
 const executable=process.env.NEXO_VERIFY_EXECUTABLE;
 app=await electron.launch({...(executable?{executablePath:executable,args:[],cwd:folder}:{args:['electron/main.cjs']}),env:{...process.env,LOCALAPPDATA:folder,NEXO_TEST_HIDE_WINDOW:'1',...(executable?{PATH:`${process.env.SystemRoot}\\System32;${process.env.SystemRoot}`,NODE_PATH:''}:{})}});
 await app.context().setOffline(true);
 const page=await app.firstWindow();page.setDefaultTimeout(7000);
 await page.getByLabel('Nome do responsável').fill('Teste navegação');
 await page.getByRole('button',{name:'Começar',exact:true}).click();
 await page.getByLabel('Senha',{exact:true}).fill('Senha-teste-123');
 await page.getByLabel('Confirmar senha').fill('Senha-teste-123');
 await page.getByRole('button',{name:'Definir senha'}).click();
 const nav=page.getByRole('navigation',{name:'Navegação principal'});
 await expect(page.getByRole('heading',{name:'Vender',exact:true})).toBeVisible();
 await expect(page.getByRole('form',{name:'Cadastro de produtos'})).toBeHidden();
 await nav.getByRole('button',{name:'Produtos',exact:true}).click();
 await expect(page.getByRole('form',{name:'Cadastro de produtos'})).toBeHidden();
 await page.getByRole('button',{name:'Novo produto'}).click();
 await page.getByRole('form',{name:'Cadastro de produtos'}).getByLabel('Nome',{exact:true}).fill('Produto simples');
 await page.getByLabel('Código interno').fill('SIMP-1');
 await page.getByLabel('Preço de venda (R$)').fill('5,00');
 await nav.getByRole('button',{name:'Caixa',exact:true}).click();
 await expect(page.getByLabel('Código interno')).toBeHidden();
 await page.getByRole('button',{name:'Abrir caixa',exact:true}).click();
 await expect(page.getByLabel('Saldo do caixa')).toContainText('R$ 0,00');
 await expect(page.getByLabel('Valor do movimento (R$)')).toBeHidden();
 await nav.getByRole('button',{name:'Produtos',exact:true}).click();
 await expect(page.getByLabel('Código interno')).toHaveValue('SIMP-1');
 await page.getByRole('button',{name:'Salvar produto'}).click();
 await expect(page.getByRole('cell',{name:'Produto simples',exact:true})).toBeVisible();
 await expect(page.getByRole('form',{name:'Cadastro de produtos'})).toBeHidden();
 await page.getByRole('button',{name:'Novo produto'}).click();
 await expect(page.getByLabel('Código interno')).toHaveValue('');
 await page.getByLabel('Código interno').fill('DESCARTAR');
 await page.getByRole('button',{name:'Cancelar',exact:true}).click();
 await page.getByRole('button',{name:'Novo produto'}).click();
 await expect(page.getByLabel('Código interno')).toHaveValue('');
 await page.getByLabel('Código interno').fill('EMPRESA-ANTERIOR');
 await page.getByLabel('Empresa em uso').selectOption('deposito-jg');
 await expect(page.getByRole('form',{name:'Cadastro de produtos'})).toBeHidden();
 await page.getByRole('button',{name:'Novo produto'}).click();
 await expect(page.getByLabel('Código interno')).toHaveValue('');
 await page.getByRole('button',{name:'Cancelar',exact:true}).click();
 await page.getByLabel('Empresa em uso').selectOption('adega-jg');
 const productId = await page.evaluate(async () => {
  const product=(await window.nexoLocal.products('adega-jg'))[0];
  const supplier=await window.nexoLocal.createPerson('adega-jg','supplier',{name:'Fornecedor teste'});
  await window.nexoLocal.receivePurchase('adega-jg',crypto.randomUUID(),{supplierId:supplier.id,items:[{productId:product.id,quantity:'2',unitCostCents:100}]});
  return product.id;
 });
 await nav.getByRole('button',{name:'Vender',exact:true}).click();
 await page.getByLabel('Produto da venda 1',{exact:true}).selectOption(productId);
 await page.getByRole('button',{name:'Concluir venda',exact:true}).click();
 await expect(page.getByRole('table',{name:'Vendas realizadas'})).toContainText('R$ 5,00');
 await nav.getByRole('button',{name:'Caixa',exact:true}).click();
 await expect(page.getByLabel('Saldo do caixa')).toContainText('R$ 5,00');
 await page.getByText('Encerrar atendimento e fechar caixa',{exact:true}).click();
 await page.getByLabel('Dinheiro contado (R$)').fill('5,00');
 await page.getByRole('button',{name:'Fechar caixa',exact:true}).click();
 await expect(page.getByRole('button',{name:'Abrir caixa',exact:true})).toBeVisible();
 await nav.getByRole('button',{name:'Mais opções'}).click();
 await expect(page.getByRole('button',{name:'Gerar backup'})).toBeHidden();
 await page.getByRole('button',{name:'Backup e dados'}).click();
 await expect(page.getByRole('button',{name:'Gerar backup'})).toBeVisible();
 await nav.getByRole('button',{name:'Estoque',exact:true}).click();
 await expect(page.getByRole('table',{name:'Saldo de estoque'})).toBeVisible();
 await expect(page.getByRole('button',{name:'Gerar backup'})).toBeHidden();
 await page.getByLabel('Empresa em uso').selectOption('deposito-jg');
 await nav.getByRole('button',{name:'Produtos',exact:true}).click();
 await expect(page.getByText('Nenhum produto cadastrado nesta empresa.')).toBeVisible();
 console.log('Navegação: uma área por vez, formulário sob demanda, rascunho preservado, caixa, apoio e isolamento aprovados.');
} finally {await app?.close();await rm(folder,{recursive:true,force:true});}
