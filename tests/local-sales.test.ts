import { expect, it } from 'vitest';
import { randomUUID } from 'node:crypto';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { openLocalDatabase } from '../src/local/sqlite';
import { prepareLocalDatabase } from '../src/local/migrations';
import { initializeLocalOwner } from '../src/local/onboarding';
import { createLocalProduct, updateLocalProduct } from '../src/local/catalog';
import { createLocalPerson } from '../src/local/people';
import { receiveLocalPurchase } from '../src/local/purchases';
import { openLocalCash, closeLocalCash, listLocalCash } from '../src/local/cash';
import { confirmLocalSale } from '../src/local/sales';
import { listLocalStock } from '../src/local/stock';
import { validateLocalBackup } from '../src/local/recovery';
it('ciclo SQLite compra/estoque/caixa/venda/receita/fechamento exato e atômico', async () => {
  const folder = await mkdtemp(path.join(tmpdir(), 'nexo-local-sale-')); const file = path.join(folder, 'active.sqlite'); let db = openLocalDatabase(file);
  try {
    await prepareLocalDatabase(db, file); const owner = await initializeLocalOwner(db, 'Responsável');
    const supplier = await createLocalPerson(db, owner.id, 'adega-jg', 'supplier', { name: 'Fornecedor' });
    const product = await createLocalProduct(db, owner.id, 'adega-jg', { name: 'Produto', internalCode: 'SALE-1', unit: 'KG', costCents: 101, priceCents: 200 });
    await receiveLocalPurchase(db, owner.id, 'adega-jg', randomUUID(), { supplierId: supplier.id, items: [{ productId: product.id, quantity: '5', unitCostCents: 101 }] });
    const body = { items: [{ productId: product.id, quantity: '1.255' }], discountCents: 1, paymentMethod: 'CASH', receivedCents: 300 };
    await expect(confirmLocalSale(db, owner.id, 'adega-jg', randomUUID(), body)).rejects.toThrow('Abra o caixa');
    const cash = await openLocalCash(db, owner.id, 'adega-jg', randomUUID(), { openingCents: 1000 });
    const key = randomUUID(); const sale = await confirmLocalSale(db, owner.id, 'adega-jg', key, body);
    expect(sale).toMatchObject({ totalCents: 250n, changeCents: 50n, replayed: false });
    expect((await confirmLocalSale(db, owner.id, 'adega-jg', key, body)).replayed).toBe(true);
    expect((await listLocalStock(db, owner.id, 'adega-jg'))[0]?.balance_milli).toBe(3745n);
    expect((await listLocalCash(db, owner.id, 'adega-jg'))[0]?.balance_cents).toBe(1250n);
    await expect(confirmLocalSale(db, owner.id, 'adega-jg', key, { ...body, notes: 'Mudou' })).rejects.toThrow('outra venda');
    await expect(confirmLocalSale(db, owner.id, 'adega-jg', randomUUID(), { ...body, items: [{ productId: product.id, quantity: '10' }], receivedCents: 9999 })).rejects.toThrow('insuficiente');
    await expect(confirmLocalSale(db, owner.id, 'adega-jg', randomUUID(), { ...body, items: [...body.items, ...body.items] })).rejects.toThrow('repetido');
    await db.exec("CREATE TRIGGER fail_sale BEFORE INSERT ON local_audit WHEN NEW.action='sale.confirmed' BEGIN SELECT RAISE(ABORT,'Falha auditoria'); END;");
    await expect(confirmLocalSale(db, owner.id, 'adega-jg', randomUUID(), body)).rejects.toThrow('Falha auditoria');
    expect(await db.query('SELECT id FROM local_sales')).toHaveLength(1);
    expect(await db.query('SELECT sale_id FROM local_sale_payments')).toHaveLength(1);
    expect(await db.query('SELECT sale_id FROM local_sale_revenues')).toHaveLength(1);
    expect((await listLocalCash(db, owner.id, 'adega-jg'))[0]?.balance_cents).toBe(1250n);
    await db.exec('DROP TRIGGER fail_sale');
    await confirmLocalSale(db, owner.id, 'adega-jg', randomUUID(), { items: [{ productId: product.id, quantity: '1' }], paymentMethod: 'PIX' });
    expect((await listLocalCash(db, owner.id, 'adega-jg'))[0]?.balance_cents).toBe(1250n);
    await updateLocalProduct(db, owner.id, 'adega-jg', product.id, { priceCents: 999, costCents: 500 });
    expect((await db.query('SELECT unit_price_cents,unit_cost_cents FROM local_sale_items WHERE sale_id=?', [sale.id]))[0]).toEqual({ unit_price_cents: 200n, unit_cost_cents: 101n });
    await closeLocalCash(db, owner.id, 'adega-jg', cash.id, { countedCents: 1250 });
    const backup = path.join(folder, 'backup.sqlite'); await db.backup(backup); validateLocalBackup(backup);
    await db.close(); db = openLocalDatabase(file); await prepareLocalDatabase(db, file);
    expect((await confirmLocalSale(db, owner.id, 'adega-jg', key, body)).replayed).toBe(true);
    expect((await listLocalStock(db, owner.id, 'adega-jg'))[0]?.balance_milli).toBe(2745n);
    expect(await db.query('SELECT SUM(amount_cents) AS total FROM local_sale_revenues')).toEqual([{ total: 450n }]);
  } finally { await db.close(); await rm(folder, { recursive: true, force: true }); }
});