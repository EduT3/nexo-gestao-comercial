import { getLocalDailyReport } from '../src/local/reports';
import { expect, it } from 'vitest';
import { randomUUID } from 'node:crypto';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { openLocalDatabase } from '../src/local/sqlite';
import { prepareLocalDatabase } from '../src/local/migrations';
import { initializeLocalOwner } from '../src/local/onboarding';
import { createLocalProduct, updateLocalProduct } from '../src/local/catalog';
import { createLocalPerson } from '../src/local/people';
import { receiveLocalPurchase } from '../src/local/purchases';
import { openLocalCash, closeLocalCash, listLocalCash } from '../src/local/cash';
import { confirmLocalSale } from '../src/local/sales';
import { cancelLocalSale } from '../src/local/cancellations';
import { listLocalStock } from '../src/local/stock';
import { getLocalFinanceSummary } from '../src/local/finance';
import { validateLocalBackup } from '../src/local/recovery';
it('cancelamento local: estorno atômico, histórico, caixa novo, reexecução e isolamento', async () => {
  const folder = await mkdtemp(path.join(tmpdir(), 'nexo-cancel-')); const file = path.join(folder, 'active.sqlite'); let db = openLocalDatabase(file);
  try {
    await prepareLocalDatabase(db, file); const owner = await initializeLocalOwner(db, 'Responsável');
    const supplier = await createLocalPerson(db, owner.id, 'adega-jg', 'supplier', { name: 'Fornecedor' });
    const product = await createLocalProduct(db, owner.id, 'adega-jg', { name: 'Produto', internalCode: 'CANCEL-1', unit: 'UNIT', costCents: 100, priceCents: 200 });
    await receiveLocalPurchase(db, owner.id, 'adega-jg', randomUUID(), { supplierId: supplier.id, items: [{ productId: product.id, quantity: '5', unitCostCents: 100 }] });
    const cash = await openLocalCash(db, owner.id, 'adega-jg', randomUUID(), { openingCents: 0 });
    const sale = await confirmLocalSale(db, owner.id, 'adega-jg', randomUUID(), { items: [{ productId: product.id, quantity: '1' }], paymentMethod: 'CASH' });
    const pix = await confirmLocalSale(db, owner.id, 'adega-jg', randomUUID(), { items: [{ productId: product.id, quantity: '1' }], paymentMethod: 'PIX' });
    const body = { reason: 'Cliente desistiu' }; const key = randomUUID();
    await expect(cancelLocalSale(db, owner.id, 'deposito-jg', sale.id, key, body)).rejects.toThrow('nesta empresa');
    await db.exec("CREATE TRIGGER fail_cancel BEFORE INSERT ON local_audit WHEN NEW.action='sale.cancelled' BEGIN SELECT RAISE(ABORT,'Falha auditoria'); END;");
    await expect(cancelLocalSale(db, owner.id, 'adega-jg', sale.id, key, body)).rejects.toThrow('Falha auditoria');
    expect(await db.query('SELECT id FROM local_sale_cancellations')).toHaveLength(0);
    expect((await listLocalStock(db, owner.id, 'adega-jg'))[0]?.balance_milli).toBe(3000n);
    expect((await listLocalCash(db, owner.id, 'adega-jg'))[0]?.balance_cents).toBe(200n);
    await db.exec('DROP TRIGGER fail_cancel');
    await closeLocalCash(db, owner.id, 'adega-jg', cash.id, { countedCents: 200 });
    await expect(cancelLocalSale(db, owner.id, 'adega-jg', sale.id, key, body)).rejects.toThrow('Abra o caixa');
    const nextCash = await openLocalCash(db, owner.id, 'adega-jg', randomUUID(), { openingCents: 199 });
    await expect(cancelLocalSale(db, owner.id, 'adega-jg', sale.id, key, body)).rejects.toThrow('insuficiente');
    await closeLocalCash(db, owner.id, 'adega-jg', nextCash.id, { countedCents: 199 });
    await openLocalCash(db, owner.id, 'adega-jg', randomUUID(), { openingCents: 200 });
    await updateLocalProduct(db, owner.id, 'adega-jg', product.id, { active: false });
    await cancelLocalSale(db, owner.id, 'adega-jg', sale.id, key, body);
    expect((await cancelLocalSale(db, owner.id, 'adega-jg', sale.id, key, body)).replayed).toBe(true);
    await expect(cancelLocalSale(db, owner.id, 'adega-jg', sale.id, key, { reason: 'Alterado' })).rejects.toThrow('outro cancelamento');
    await expect(cancelLocalSale(db, owner.id, 'adega-jg', sale.id, randomUUID(), body)).rejects.toThrow('já cancelada');
    await cancelLocalSale(db, owner.id, 'adega-jg', pix.id, randomUUID(), body);
    expect((await listLocalStock(db, owner.id, 'adega-jg'))[0]?.balance_milli).toBe(5000n);
    const sessions = await listLocalCash(db, owner.id, 'adega-jg');
    expect(sessions.find(row => row.id === cash.id)?.closure).toMatchObject({ expected_cents: 200n });
    expect(sessions.find(row => row.closed === 0n)?.balance_cents).toBe(0n);
    expect(await db.query('SELECT id FROM local_sales')).toHaveLength(2);
    expect(await db.query('SELECT sale_id FROM local_sale_revenues')).toHaveLength(2);
    expect(await db.query('SELECT SUM(amount_cents) AS total FROM local_sale_cancellations')).toEqual([{ total: 400n }]);
    expect(await getLocalFinanceSummary(db, owner.id, 'adega-jg')).toMatchObject({ revenueCents: 400n, reversedCents: 400n, netRevenueCents: 0n });
    expect(await getLocalFinanceSummary(db, owner.id, 'deposito-jg')).toMatchObject({ revenueCents: 0n, reversedCents: 0n, netRevenueCents: 0n });
    const period = { from: '2000-01-01T00:00:00.000Z', to: '2100-01-01T00:00:00.000Z' };
    const report = await getLocalDailyReport(db, owner.id, 'adega-jg', period);
    expect(report).toMatchObject({ saleCount: 2, grossSalesCents: 400n, cancelledSalesCents: 400n, netSalesCents: 0n, receivedCents: 0n, paidCents: 0n, financialBalanceCents: 0n });
    expect(report.byPayment).toEqual([{ method: 'CASH', amountCents: 200n },{ method: 'PIX', amountCents: 200n },{ method: 'DEBIT', amountCents: 0n },{ method: 'CREDIT', amountCents: 0n }]);
    expect(report.products).toEqual([{ productId: product.id, name: 'Produto', quantityMilli: 2000n }]);
    expect(await getLocalDailyReport(db, owner.id, 'deposito-jg', period)).toMatchObject({ saleCount: 0, grossSalesCents: 0n });
    expect(await getLocalDailyReport(db, owner.id, 'adega-jg', { from: '2200-01-01T00:00:00.000Z', to: '2200-01-02T00:00:00.000Z' })).toMatchObject({ saleCount: 0, financialBalanceCents: 0n });
    await expect(getLocalDailyReport(db, owner.id, 'adega-jg', { from: period.to, to: period.from })).rejects.toThrow('início');
    await expect(db.query('DELETE FROM local_sale_cancellations')).rejects.toThrow('imutável');
    const backup = path.join(folder, 'backup.sqlite'); await db.backup(backup); validateLocalBackup(backup);
    await db.close(); db = openLocalDatabase(file); await prepareLocalDatabase(db, file);
    expect((await cancelLocalSale(db, owner.id, 'adega-jg', sale.id, key, body)).replayed).toBe(true);
    await db.query("UPDATE local_memberships SET role='OPERADOR' WHERE company_id=? AND user_id=?", ['adega-jg', owner.id]);
    await expect(cancelLocalSale(db, owner.id, 'adega-jg', sale.id, key, body)).rejects.toThrow('perfil');
    await expect(getLocalDailyReport(db, owner.id, 'adega-jg', { from: '2000-01-01T00:00:00.000Z', to: '2100-01-01T00:00:00.000Z' })).rejects.toThrow('perfil');
  } finally { await db.close(); await rm(folder, { recursive: true, force: true }); }
});