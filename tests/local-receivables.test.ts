import { getLocalDailyReport } from '../src/local/reports';
import { getLocalFinanceSummary } from '../src/local/finance';
import { expect, it } from 'vitest';
import { randomUUID } from 'node:crypto';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { openLocalDatabase } from '../src/local/sqlite';
import { prepareLocalDatabase } from '../src/local/migrations';
import { initializeLocalOwner } from '../src/local/onboarding';
import { createLocalPerson } from '../src/local/people';
import { createLocalReceivable, receiveLocalReceivable, reverseLocalReceivableReceipt } from '../src/local/receivables';
import { openLocalCash, listLocalCash } from '../src/local/cash';
import { validateLocalBackup } from '../src/local/recovery';
it('recebível local: cliente isolado, recebimento/estorno exatos, rollback e reexecução', async () => {
 const folder = await mkdtemp(path.join(tmpdir(), 'nexo-receivable-')); const file = path.join(folder, 'base.sqlite'); let db = openLocalDatabase(file);
 try {
  await prepareLocalDatabase(db, file); const owner = await initializeLocalOwner(db, 'Responsável');
  const customer = await createLocalPerson(db, owner.id, 'adega-jg', 'customer', { name: 'Cliente' });
  const body = { customerId: customer.id, description: 'Conta do cliente', category: 'Recebimentos', amountCents: 123, dueDate: '2026-10-01' }; const createKey = randomUUID();
  await expect(createLocalReceivable(db, owner.id, 'deposito-jg', randomUUID(), body)).rejects.toThrow('cliente ativo');
  const account = await createLocalReceivable(db, owner.id, 'adega-jg', createKey, body);
  expect((await createLocalReceivable(db, owner.id, 'adega-jg', createKey, body)).replayed).toBe(true);
  await expect(createLocalReceivable(db, owner.id, 'adega-jg', createKey, { ...body, amountCents: 124 })).rejects.toThrow('outra conta');
  const key = randomUUID(); const input = { method: 'CASH' };
  await expect(receiveLocalReceivable(db, owner.id, 'adega-jg', account.id, key, input)).rejects.toThrow('Abra o caixa');
  await openLocalCash(db, owner.id, 'adega-jg', randomUUID(), { openingCents: 0 });
  await db.exec("CREATE TRIGGER fail_receipt BEFORE INSERT ON local_audit WHEN NEW.action='receivable.received' BEGIN SELECT RAISE(ABORT,'Falha auditoria'); END;");
  await expect(receiveLocalReceivable(db, owner.id, 'adega-jg', account.id, key, input)).rejects.toThrow('Falha auditoria');
  expect((await listLocalCash(db, owner.id, 'adega-jg'))[0]?.balance_cents).toBe(0n);
  expect(await db.query('SELECT id FROM local_receivable_receipts')).toHaveLength(0);
  await db.exec('DROP TRIGGER fail_receipt');
  const receipt = await receiveLocalReceivable(db, owner.id, 'adega-jg', account.id, key, input);
  expect((await receiveLocalReceivable(db, owner.id, 'adega-jg', account.id, key, input)).replayed).toBe(true);
  expect((await listLocalCash(db, owner.id, 'adega-jg'))[0]?.balance_cents).toBe(123n);
  await expect(receiveLocalReceivable(db, owner.id, 'adega-jg', account.id, randomUUID(), input)).rejects.toThrow('já está recebida');
  expect(await getLocalFinanceSummary(db, owner.id, 'adega-jg')).toMatchObject({ receivedCents: 123n, reversedReceiptCents: 0n, netReceivedCents: 123n, totalIncomeCents: 123n, financialBalanceCents: 123n });
  const period = { from: '2000-01-01T00:00:00.000Z', to: '2100-01-01T00:00:00.000Z' };
  expect(await getLocalDailyReport(db, owner.id, 'adega-jg', period)).toMatchObject({ receivedCents: 123n, paidCents: 0n, financialBalanceCents: 123n });
  expect(await getLocalFinanceSummary(db, owner.id, 'deposito-jg')).toMatchObject({ receivedCents: 0n, netReceivedCents: 0n, financialBalanceCents: 0n });
  const reverseKey = randomUUID(); const reason = { reason: 'Recebimento incorreto' };
  await db.exec("CREATE TRIGGER fail_receipt_reverse BEFORE INSERT ON local_audit WHEN NEW.action='receivable.receipt_reversed' BEGIN SELECT RAISE(ABORT,'Falha auditoria'); END;");
  await expect(reverseLocalReceivableReceipt(db, owner.id, 'adega-jg', receipt.id, reverseKey, reason)).rejects.toThrow('Falha auditoria');
  expect((await listLocalCash(db, owner.id, 'adega-jg'))[0]?.balance_cents).toBe(123n);
  await db.exec('DROP TRIGGER fail_receipt_reverse');
  await reverseLocalReceivableReceipt(db, owner.id, 'adega-jg', receipt.id, reverseKey, reason);
  expect((await listLocalCash(db, owner.id, 'adega-jg'))[0]?.balance_cents).toBe(0n);
  expect(await getLocalFinanceSummary(db, owner.id, 'adega-jg')).toMatchObject({ receivedCents: 123n, reversedReceiptCents: 123n, netReceivedCents: 0n, financialBalanceCents: 0n });
  expect(await getLocalDailyReport(db, owner.id, 'adega-jg', period)).toMatchObject({ receivedCents: 0n, financialBalanceCents: 0n });
  await receiveLocalReceivable(db, owner.id, 'adega-jg', account.id, randomUUID(), { method: 'PIX' });
  expect(await getLocalFinanceSummary(db, owner.id, 'adega-jg')).toMatchObject({ receivedCents: 246n, reversedReceiptCents: 123n, netReceivedCents: 123n });
  expect(await getLocalDailyReport(db, owner.id, 'adega-jg', period)).toMatchObject({ receivedCents: 123n, financialBalanceCents: 123n });
  expect((await listLocalCash(db, owner.id, 'adega-jg'))[0]?.balance_cents).toBe(0n);
  const backup = path.join(folder, 'backup.sqlite'); await db.backup(backup); validateLocalBackup(backup);
  await db.close(); db = openLocalDatabase(file); await prepareLocalDatabase(db, file);
  expect((await reverseLocalReceivableReceipt(db, owner.id, 'adega-jg', receipt.id, reverseKey, reason)).replayed).toBe(true);
  await db.query("UPDATE local_memberships SET role='OPERADOR' WHERE company_id=? AND user_id=?", ['adega-jg', owner.id]);
  await expect(createLocalReceivable(db, owner.id, 'adega-jg', createKey, body)).rejects.toThrow('perfil');
  await expect(getLocalFinanceSummary(db, owner.id, 'adega-jg')).rejects.toThrow('perfil');
 } finally { await db.close(); await rm(folder, { recursive: true, force: true }); }
});