import { getLocalDailyReport } from '../src/local/reports';
import { expect, it } from 'vitest';
import { randomUUID } from 'node:crypto';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { openLocalDatabase } from '../src/local/sqlite';
import { prepareLocalDatabase } from '../src/local/migrations';
import { initializeLocalOwner } from '../src/local/onboarding';
import { createLocalProduct } from '../src/local/catalog';
import { createLocalPerson } from '../src/local/people';
import { receiveLocalPurchase } from '../src/local/purchases';
import { openLocalCash, listLocalCash } from '../src/local/cash';
import { payLocalPayable, reverseLocalPayablePayment } from '../src/local/settlements';
import { validateLocalBackup } from '../src/local/recovery';
it('pagamento/estorno local: caixa exato, reexecução, reabertura do título e rollback', async () => {
 const folder = await mkdtemp(path.join(tmpdir(), 'nexo-payable-')); const file = path.join(folder, 'base.sqlite'); let db = openLocalDatabase(file);
 try {
  await prepareLocalDatabase(db, file); const owner = await initializeLocalOwner(db, 'Responsável');
  const supplier = await createLocalPerson(db, owner.id, 'adega-jg', 'supplier', { name: 'Fornecedor' });
  const product = await createLocalProduct(db, owner.id, 'adega-jg', { name: 'Produto', internalCode: 'PAY-1', unit: 'UNIT', costCents: 100, priceCents: 200 });
  await receiveLocalPurchase(db, owner.id, 'adega-jg', randomUUID(), { supplierId: supplier.id, items: [{ productId: product.id, quantity: '1', unitCostCents: 100 }], payable: { dueDate: '2026-10-01' } });
  const payable = String((await db.query('SELECT id FROM local_purchase_payables'))[0]?.id); const key = randomUUID(); const body = { method: 'CASH', notes: 'Quitação' };
  await expect(payLocalPayable(db, owner.id, 'adega-jg', payable, key, body)).rejects.toThrow('Abra o caixa');
  await openLocalCash(db, owner.id, 'adega-jg', randomUUID(), { openingCents: 200 });
  await expect(payLocalPayable(db, owner.id, 'deposito-jg', payable, key, body)).rejects.toThrow('nesta empresa');
  await db.exec("CREATE TRIGGER fail_pay BEFORE INSERT ON local_audit WHEN NEW.action='payable.paid' BEGIN SELECT RAISE(ABORT,'Falha auditoria'); END;");
  await expect(payLocalPayable(db, owner.id, 'adega-jg', payable, key, body)).rejects.toThrow('Falha auditoria');
  expect((await listLocalCash(db, owner.id, 'adega-jg'))[0]?.balance_cents).toBe(200n);
  expect(await db.query('SELECT id FROM local_payable_payments')).toHaveLength(0);
  await db.exec('DROP TRIGGER fail_pay');
  const [payment, repeated] = await Promise.all([payLocalPayable(db, owner.id, 'adega-jg', payable, key, body), payLocalPayable(db, owner.id, 'adega-jg', payable, key, body)]);
  expect([payment.replayed, repeated.replayed]).toEqual([false,true]);
  expect((await listLocalCash(db, owner.id, 'adega-jg'))[0]?.balance_cents).toBe(100n);
  const period = { from: '2000-01-01T00:00:00.000Z', to: '2100-01-01T00:00:00.000Z' };
  expect(await getLocalDailyReport(db, owner.id, 'adega-jg', period)).toMatchObject({ paidCents: 100n, financialBalanceCents: -100n });
  await expect(payLocalPayable(db, owner.id, 'adega-jg', payable, randomUUID(), body)).rejects.toThrow('já está paga');
  const reversalKey = randomUUID(); const reason = { reason: 'Pagamento incorreto' };
  await db.exec("CREATE TRIGGER fail_reverse BEFORE INSERT ON local_audit WHEN NEW.action='payable.payment_reversed' BEGIN SELECT RAISE(ABORT,'Falha auditoria'); END;");
  await expect(reverseLocalPayablePayment(db, owner.id, 'adega-jg', payment.id, reversalKey, reason)).rejects.toThrow('Falha auditoria');
  expect((await listLocalCash(db, owner.id, 'adega-jg'))[0]?.balance_cents).toBe(100n);
  await db.exec('DROP TRIGGER fail_reverse');
  await reverseLocalPayablePayment(db, owner.id, 'adega-jg', payment.id, reversalKey, reason);
  expect(await getLocalDailyReport(db, owner.id, 'adega-jg', period)).toMatchObject({ paidCents: 0n, financialBalanceCents: 0n });
  expect((await reverseLocalPayablePayment(db, owner.id, 'adega-jg', payment.id, reversalKey, reason)).replayed).toBe(true);
  expect((await listLocalCash(db, owner.id, 'adega-jg'))[0]?.balance_cents).toBe(200n);
  await payLocalPayable(db, owner.id, 'adega-jg', payable, randomUUID(), { method: 'PIX' });
  expect((await listLocalCash(db, owner.id, 'adega-jg'))[0]?.balance_cents).toBe(200n);
  expect(await getLocalDailyReport(db, owner.id, 'adega-jg', period)).toMatchObject({ paidCents: 100n, financialBalanceCents: -100n });
  await expect(db.query('DELETE FROM local_payable_payments')).rejects.toThrow('imutável');
  const backup = path.join(folder, 'backup.sqlite'); await db.backup(backup); validateLocalBackup(backup);
  await db.close(); db = openLocalDatabase(file); await prepareLocalDatabase(db, file);
  expect((await payLocalPayable(db, owner.id, 'adega-jg', payable, key, body)).replayed).toBe(true);
  await db.query("UPDATE local_memberships SET role='OPERADOR' WHERE company_id=? AND user_id=?", ['adega-jg', owner.id]);
  await expect(payLocalPayable(db, owner.id, 'adega-jg', payable, key, body)).rejects.toThrow('perfil');
 } finally { await db.close(); await rm(folder, { recursive: true, force: true }); }
});